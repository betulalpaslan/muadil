    public static async Task DoldurAsync(MuadilDbContext db, CancellationToken ct = default)
    {
        var bos = await db.Notalar.Where(n => n.Aciklama == null || n.Aciklama == "").ToListAsync(ct);
        foreach (var nota in bos)
            if (Liste.TryGetValue(nota.Ad, out var aciklama))
                nota.Aciklama = aciklama;

        if (db.ChangeTracker.HasChanges())
            await db.SaveChangesAsync(ct);
    }

